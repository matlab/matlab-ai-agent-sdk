    methods (Test, TestTags = {'Unit'})
        function tools_includeInputSchema(testCase)
            client = aisdk.MCPClient("mock", Transport="mock");
            schema = client.Tools(1).InputSchema;
            testCase.verifyTrue(isstruct(schema));
            testCase.verifyTrue(isfield(schema, "properties"));
            testCase.verifyEqual(schema.type, 'object');
        end

        function tools_evaluate_resultHasIsErrorFalse(testCase)
            import matlab.unittest.constraints.HasField
            client = aisdk.MCPClient("mock", Transport="mock");
            result = client.Tools(1).evaluate(struct("param1", "hello"));
            testCase.verifyThat(result, HasField("isError"));
            testCase.verifyFalse(result.isError);
        end

        function callTool_structArg_returnsResult(testCase)
            % callTool is a private seam; the struct-argument form is not
            % reachable through the public Tools array.
            client = aisdk.MCPClient("mock", Transport="mock");
            tool = struct("name", "example-tool", ...
                "arguments", struct("param1", "hello", "param2", 42));
            result = client.callTool(tool);
            testCase.verifyEqual(result.content.text, 'Example result');
        end

