    methods (Test, TestTags = {'Unit'})
        function callTool_httpError_producesCorrectErrorId(testCase, HttpErrorCase)
            c = HttpErrorCase;
            client = aisdk.MCPClient("mock", Transport="mock");
            testCase.verifyError( ...
                @() client.callTool("__throw_http_error", "statusCode", c.statusCode), ...
                c.expectedId);
        end

        function throwServerError_producesCorrectErrorId(testCase, ThrowServerErrorCase)
            c = ThrowServerErrorCase;
            testCase.verifyError( ...
                @() aisdk.MCPClient.throwServerError(c.code, "test"), ...
                c.expectedId);
        end

        function throwMexError_producesCorrectErrorId(testCase, MexErrorCase)
            c = MexErrorCase;
            testCase.verifyError( ...
                @() aisdk.MCPClient.throwMexError( ...
                    MException(c.identifier, "%s", "test detail")), ...
                c.expectedId);
        end

        function throwMexError_localFault_keepsTheDetailedMessage(testCase)
            % A bad argument is a local fault, not a server error, and the
            % MEX message is the only thing that says which argument.
            err = testCase.captureError( ...
                @() aisdk.MCPClient.throwMexError(MException( ...
                    "mcpclient_mex:badInput", "%s", "Argument 2 must be a string")));
            testCase.verifySubstring(err.message, "Argument 2 must be a string");
        end

        function resolveTransport_detectsCorrectType(testCase, ResolveTransportCase)
            c = ResolveTransportCase;
            [type, url, args] = aisdk.MCPClient.resolveTransport( ...
                c.endpoint, c.transport);
            testCase.verifyEqual(type, c.expectedType);
            testCase.verifyEqual(url, c.expectedUrl);
            testCase.verifyEqual(args, c.expectedArgs);
        end

        function resolveTransport_stringArrayEndpoint_detectsStdio(testCase)
            [type, url, args] = aisdk.MCPClient.resolveTransport( ...
                ["/usr/local/bin/srv", "--verbose"], "auto");
            testCase.verifyEqual(type, "stdio");
            testCase.verifyEqual(url, "/usr/local/bin/srv");
            testCase.verifyEqual(args, "--verbose");
        end

        function resolveTransport_nonScalarEndpointWithHttp_errors(testCase)
            testCase.verifyError( ...
                @() aisdk.MCPClient.resolveTransport( ...
                    ["http://a", "http://b"], "sse"), ...
                "aisdk:MCPClient:nonScalarURL");
        end

        function resolveTransport_transportMismatch_errors(testCase, TransportMismatchCase)
            c = TransportMismatchCase;
            testCase.verifyError( ...
                @() aisdk.MCPClient.resolveTransport(c.endpoint, c.transport), ...
