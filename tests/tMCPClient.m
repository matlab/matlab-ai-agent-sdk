            client = aisdk.MCPClient("mock", Transport="mock");
            tools = client.Tools;
            result = tools(1).evaluate(struct("param1", "hello", "param2", 42));
            testCase.verifyEqual(result.content.text, 'Example result');
        end

        function callTool_viaEvaluate_preservesArrayParams(testCase)
            client = aisdk.MCPClient("mock", Transport="mock");
            tools = client.Tools;
            args = struct("param1", "hello");
            args.items = {"a", "b"};
            result = tools(1).evaluate(args);
            testCase.verifyEqual(result.content.text, 'Example result');
        end

        function callTool_nonAsciiArgument_roundTripsUnchanged(testCase, NonAsciiText)
            % MCP is UTF-8 throughout. Argument values must survive the trip
            % out through the MEX and back, unchanged. The mock's echo tool
            % returns its arguments JSON-encoded, so any mangling shows up in
            % the decoded result.
            client = aisdk.MCPClient("mock", Transport="mock");
            echoTool = client.Tools([client.Tools.Name] == "echo");
            testCase.assertNumElements(echoTool, 1, ...
                "mock should expose one echo tool");

            result = echoTool.evaluate(struct("text", NonAsciiText));

            echoed = jsondecode(string(result.content.text));
            testCase.verifyEqual(string(echoed.text), NonAsciiText);
        end

        function callTool_nonAsciiResult_isReturnedUnchanged(testCase)
            % The response direction alone: the request is pure ASCII, only
            % the server's reply carries non-ASCII text.
            client = aisdk.MCPClient("mock", Transport="mock");
            echoTool = client.Tools([client.Tools.Name] == "echo");

            result = echoTool.evaluate(struct("text", "café 東京 🎉"));

            testCase.verifySubstring(string(result.content.text), "café 東京 🎉");
        end

        function connect_nonAsciiEndpoint_succeeds(testCase)
            % Endpoints reach the MEX as MATLAB strings, the same path a
            % stdio command in a folder with a non-ASCII name takes. The mock
            % ignores its URL, so this isolates the conversion.
            client = aisdk.MCPClient("mock-café-東京-🎉", Transport="mock");
            testCase.verifyNotEmpty(client.Tools);
        end

        function constructor_timeOutOption_setsProperty(testCase)
            % TimeOut has to be settable at construction: the first listTools
            % runs inside the constructor, so a value assigned afterwards
            % arrives too late to govern it.
            client = aisdk.MCPClient("mock", Transport="mock", TimeOut=5);
            testCase.verifyEqual(client.TimeOut, 5);
        end

        function constructor_withoutTimeOut_usesDefault(testCase)
            client = aisdk.MCPClient("mock", Transport="mock");
            testCase.verifyEqual(client.TimeOut, 120);
        end

