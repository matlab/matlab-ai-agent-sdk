        end

        function emptyToolPrefix_doesNotPrefix(testCase)
            client = aisdk.MCPClient("mock", Transport="mock", ...
                ToolPrefix="");
            testCase.verifyEqual(client.Tools(1).Name, "example-tool");
        end

        function saveAndLoad_restoresToolsAndCanCallThem(testCase)
            client = aisdk.MCPClient("mock", Transport="mock", ...
                ToolPrefix="srv");
            testCase.verifyNotEmpty(client.Tools);

            f = [tempname, '.mat'];
            testCase.addTeardown(@() delete(f));
            save(f, "client");
            loaded = load(f);

            testCase.verifyNotEmpty(loaded.client.Tools);
            testCase.verifyEqual(loaded.client.Tools(1).Name, "srv_example-tool");
            % The loaded client must be functional — its tools can be evaluated.
            result = loaded.client.Tools(1).evaluate(struct("param1", "hi"));
            testCase.verifyEqual(result.content.text, 'Example result');
        end
    end

