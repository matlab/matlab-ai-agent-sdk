function snap = solutionSnapshot(solution)
%solutionSnapshot JSON-friendly outcome metrics for a LUTSolution.
%   SNAP = solutionSnapshot(SOLUTION) returns a plain struct capturing the
%   feasibility, error, memory, and table metrics of SOLUTION. Both
%   inspectSolution (for its report) and saveContract (for the persisted
%   "results" block) build on this, so the two never drift. Read-only.

% Copyright 2026 The MathWorks, Inc.

    arguments
        solution
    end

    err = getErrorValue(solution);
    td = solution.TableData;
    bpCounts = cellfun(@numel, td.BreakpointValues);

    snap = struct( ...
        "solutionID", double(solution.ID), ...
        "feasible", logical(strcmp(string(solution.Feasible), "true")), ...
        "maxError", err.MaxErrorInSolution, ...
        "errorUpperBound", err.ErrorUpperBound, ...
        "memoryBytes", totalMemoryUsage(solution, 'bytes'), ...
        "memoryBits", totalMemoryUsage(solution, 'bits'), ...
        "tableSize", numel(td.TableValues), ...
        "numInputs", numel(td.BreakpointValues), ...
        "breakpointsPerDim", bpCounts(:).', ...
        "tableDataType", string(td.TableDataType.tostring()), ...
        "interpolation", string(td.Interpolation), ...
        "evenSpacing", logical(td.IsEvenSpacing));

    % PercentReduction is only meaningful for Simulink-block sources.
    if ~isinf(solution.PercentReduction)
        snap.percentReduction = solution.PercentReduction;
    end
end
