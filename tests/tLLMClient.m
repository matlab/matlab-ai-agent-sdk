classdef tLLMClient < matlab.unittest.TestCase
% Tests for the LLMClient factory function.

%   Copyright 2026 The MathWorks, Inc.

    properties (TestParameter)
        ApiConfig = struct( ...
            "openai", struct("api", "openai", "model", "gpt-4o", "class", "aisdk.client.OpenAIClient"), ...
            "openai_responses", struct("api", "openai-responses", "model", "gpt-4o", "class", "aisdk.client.OpenAIResponsesClient"), ...
            "ollama", struct("api", "ollama", "model", "llama2", "class", "aisdk.client.OllamaClient"));

        ChatCompletionsOnlyOption = struct( ...
            "StopSequences",    struct("prop", "StopSequences",    "value", "stop"), ...
            "PresencePenalty",  struct("prop", "PresencePenalty",  "value", 0.5), ...
            "FrequencyPenalty", struct("prop", "FrequencyPenalty", "value", 0.4));

        PassThroughConfig = struct( ...
            "openai", struct("api", "openai", "model", "gpt-4o", ...
                "options", struct( ...
                    "Temperature", 0.5, "TopP", 0.9, "StopSequences", ["stop1", "stop2"], ...
                    "MaxNumTokens", 100, "PresencePenalty", 0.3, "FrequencyPenalty", 0.4, ...
                    "ResponseFormat", "json", "ReasoningEffort", "high", "Verbosity", "low", ...
                    "TimeOut", 30, "StreamFcn", @(x) disp(x)), ...
                "baseURL", "https://fake.endpoint", ...
                "expectedBaseURL", "https://fake.endpoint/chat/completions"), ...
            "openai_responses", struct("api", "openai-responses", "model", "gpt-4o", ...
                "options", struct( ...
                    "Temperature", 0.5, "TopP", 0.9, ...
                    "MaxNumTokens", 100, ...
                    "ResponseFormat", "json", "ReasoningEffort", "high", "Verbosity", "low", ...
                    "TimeOut", 30, "StreamFcn", @(x) disp(x)), ...
                "baseURL", "https://fake.endpoint", ...
                "expectedBaseURL", "https://fake.endpoint/responses"), ...
            "ollama", struct("api", "ollama", "model", "llama2", ...
                "options", struct( ...
                    "Temperature", 0.5, "TopP", 0.9, "MinP", 0.1, "TopK", 50, ...
                    "TailFreeSamplingZ", 0.95, "StopSequences", ["stop1", "stop2"], ...
                    "MaxNumTokens", 100, "ResponseFormat", "json", ...
                    "TimeOut", 30, "StreamFcn", @(x) disp(x)), ...
                "baseURL", "http://localhost:11434", ...
                "expectedBaseURL", "http://localhost:11434/api/chat"));
    end

    methods (Test, TestTags = {'Unit'})
        function createsCorrectClientType(testCase, ApiConfig)
            client = aisdk.LLMClient(ApiConfig.api, ApiConfig.model);
            testCase.verifyClass(client, ApiConfig.class);
            testCase.verifyEqual(client.ModelName, ApiConfig.model);
        end

        function openaiResponses_withChatCompletionsOnlyOption_throwsUnsupportedParameterError(testCase, ChatCompletionsOnlyOption)
            % Identifier only: messages come from MessageCatalog, which could
            % be localized, so their wording is no contract. Asserting that
            % the error names which option was refused needs the matcher
            % extracted out of createClient, a source change not yet made.
            testCase.verifyError( ...
                @() aisdk.LLMClient("openai-responses", "gpt-4o", ...
                    ChatCompletionsOnlyOption.prop, ChatCompletionsOnlyOption.value), ...
                "aisdk:parameterUnsupportedByResponsesAPI");
        end

        function provider_withNameValuePairs_setsClientProperties(testCase, PassThroughConfig)
            nvp = namedargs2cell(PassThroughConfig.options);
            client = aisdk.LLMClient(PassThroughConfig.api, PassThroughConfig.model, nvp{:}, ...
                BaseURL=PassThroughConfig.baseURL);
            for name = string(fieldnames(PassThroughConfig.options))'
                testCase.verifyEqual(client.(name), PassThroughConfig.options.(name), name);
            end
            testCase.verifyEqual(client.BaseURL, PassThroughConfig.expectedBaseURL);
        end
    end

    methods (Test, TestTags = {'Unit'})
        function invalidApiErrors(testCase)
            testCase.verifyError(...
                @() aisdk.LLMClient("someAPIThatDoesNotExist", "gpt-4o"), ...
                "MATLAB:validators:mustBeMember");
        end

        function errorWhenModelNameOmitted(testCase)
            testCase.verifyError(...
                @() aisdk.LLMClient("openai"), ...
                "MATLAB:minrhs");
        end

        function errorWhenAllArgsOmitted(testCase)
            testCase.verifyError(...
                @() aisdk.LLMClient(), ...
                "MATLAB:minrhs");
        end
    end

end
