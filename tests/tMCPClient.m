        end

        function resolveTransport_transportMismatch_messageNamesAlternativeTransport(testCase)
            % The message must be actionable: it names the transport to use
            % instead. The endpoint is deliberately not quoted back, since
            % the caller just passed it in.
            err = testCase.captureError( ...
                @() aisdk.MCPClient.resolveTransport( ...
                    "http://localhost:8765/mcp", "stdio"));
            testCase.verifySubstring(err.message, "streamable-http");

            err = testCase.captureError( ...
                @() aisdk.MCPClient.resolveTransport("my-server --port 1", "sse"));
            testCase.verifySubstring(err.message, "stdio");
            % Also covers the placeholder actually being filled in.
            testCase.verifySubstring(err.message, "Transport=""sse""");
        end

