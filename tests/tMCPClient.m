            client = aisdk.MCPClient("mock", Transport="mock", ...
                ToolPrefix="astro");
            testCase.verifyEqual(client.Tools(1).Name, "astro_example-tool");
        end

        function toolPrefix_prefixedTool_isCallable(testCase)
            % The public tool carries the prefixed name but still resolves
            % to the raw server tool when evaluated.
            client = aisdk.MCPClient("mock", Transport="mock", ...
                ToolPrefix="astro");
            tool = client.Tools(1);
            testCase.verifyEqual(tool.Name, "astro_example-tool");
            result = tool.evaluate(struct("param1", "hello"));
            testCase.verifyEqual(result.content.text, 'Example result');
        end

        function toolPrefix_callToolWithPrefix_succeeds(testCase)
            % callTool is a private seam; the prefixed-name resolution path
            % is not reachable through the public Tools array.
            client = aisdk.MCPClient("mock", Transport="mock", ...
                ToolPrefix="astro");
            result = client.callTool("astro_example-tool", "param1", "hello");
            testCase.verifyEqual(result.content.text, 'Example result');
        end

        function toolPrefixWithInvalidChars_errors(testCase)
            testCase.verifyError(...
                @() aisdk.MCPClient("mock", Transport="mock", ...
                    ToolPrefix="bad-name"), ...
                "aisdk:MCPClient:invalidToolPrefix");
            testCase.verifyError(...
                @() aisdk.MCPClient("mock", Transport="mock", ...
